namespace Nantuc.Kernel.Common;

/// <summary>
/// Разрядность (размер) операнда памяти/регистра для инструкций загрузки-сохранения.
/// </summary>
/// <remarks>
/// <para>
/// Кодируется двумя битами в слове инструкции и извлекается декодером
/// (<c>InstructionDecoder.GetDataSizeCode</c>) для опкодов группы работы с памятью:
/// <see cref="OpCode.LOAD"/>, <see cref="OpCode.STORE"/>, <see cref="OpCode.LOAD_IND"/>,
/// <see cref="OpCode.STORE_IND"/> и их <c>_UNSAFE</c>-вариантов.
/// </para>
/// <para>
/// Числовые значения выбраны так, чтобы совпадать с двоичным кодом в инструкции:
/// <c>00</c> → 8 бит, <c>01</c> → 16 бит, <c>10</c> → 32 бита, <c>11</c> → 64 бита.
/// Менять значения без изменения декодера нельзя.
/// </para>
/// </remarks>
public enum OpCodeSize
{
    /// <summary>
    /// Разрядность 8 бит (1 байт). Код в инструкции: <c>0b00</c>.
    /// </summary>
    S8 = 0b00,

    /// <summary>
    /// Разрядность 16 бит (2 байта). Код в инструкции: <c>0b01</c>.
    /// </summary>
    S16 = 0b01,

    /// <summary>
    /// Разрядность 32 бита (4 байта). Код в инструкции: <c>0b10</c>.
    /// </summary>
    S32 = 0b10,

    /// <summary>
    /// Разрядность 64 бита (8 байт). Код в инструкции: <c>0b11</c>.
    /// </summary>
    S64 = 0b11,
}