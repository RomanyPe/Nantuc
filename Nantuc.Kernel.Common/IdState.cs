namespace Nantuc.Kernel.Common;

/// <summary>
/// Статус идентификатора (Id), присланного от внешней системы.
/// </summary>
/// <remarks>
/// <para>
/// Используется для интерпретации результата регистрации/валидации Id:
/// положительное решение — <see cref="Valid"/>, иначе — одна из причин отказа.
/// </para>
/// <para>
/// Значение по умолчанию (ноль) намеренно отдано <see cref="Unknown"/>,
/// чтобы неинициализированный статус не воспринимался как успешный.
/// Числовые значения зафиксированы явно и являются частью контракта —
/// их изменение сломает совместимость с уже сохранёнными/переданными данными.
/// </para>
/// </remarks>
public enum IdState
{
    /// <summary>
    /// Статус не определён. Значение по умолчанию; трактуется как ошибка/неготовность.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Id валиден и принят системой.
    /// </summary>
    Valid = 1,

    /// <summary>
    /// Id не был присвоен системой (например, регистрация ещё не выполнялась).
    /// </summary>
    NotAssigned = -1,

    /// <summary>
    /// Id вышел за допустимый диапазон значений.
    /// </summary>
    OutOfRange = -2,

    /// <summary>
    /// Нет свободного слота для регистрации нового Id.
    /// </summary>
    NoFreeSlot = -3,

    /// <summary>
    /// Id отклонён системой (например, не прошёл проверку политики/прав).
    /// </summary>
    Rejected = -4,
}