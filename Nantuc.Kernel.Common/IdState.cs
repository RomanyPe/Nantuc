namespace Nantuc.Kernel.Common;

/// <summary>
/// Статус идентификатора (Id), присланного от внешней системы.
/// </summary>
/// <remarks>
/// <para>
/// Используется для интерпретации результата регистрации/валидации Id:
/// положительное решение — <see cref="Valid"/>, иначе — одна из причин отказа.
/// </para>
/// <para>
/// Числовые значения зафиксированы явно и являются частью контракта —
/// их изменение сломает совместимость с уже сохранёнными/переданными данными.
/// </para>
/// <para>
/// <b>Внимание:</b> значение по умолчанию (<c>0</c>) соответствует
/// <see cref="Valid"/>. Это значит, что неинициализированное поле типа
/// <see cref="IdState"/> будет интерпретировано как успешный статус.
/// Если нужно отличать «не инициализировано» от «валидно», используйте
/// nullable-тип (<c>IdState?</c>) либо явную инициализацию
/// значением <see cref="Unknown"/>.
/// </para>
/// </remarks>
public enum IdState
{
    /// <summary>
    /// Id валиден и принят системой.
    /// </summary>
    /// <remarks>
    /// Соответствует неотрицательным значениям Id (<c>&gt;= 0</c>).
    /// Является значением по умолчанию для <see cref="IdState"/>.
    /// </remarks>
    Valid = 0,

    /// <summary>
    /// Id не был присвоен системой (например, регистрация ещё не выполнялась).
    /// </summary>
    NotAssigned = -1,

    /// <summary>
    /// Id вышел за допустимый диапазон значений.
    /// </summary>
    OutOfRange = -2,

    /// <summary>
    /// Нет свободного слота для регистрации нового Id.
    /// </summary>
    NoFreeSlot = -3,

    /// <summary>
    /// Id отклонён системой (например, не прошёл проверку политики/прав).
    /// </summary>
    Rejected = -4,

    /// <summary>
    /// Статус не определён.
    /// </summary>
    /// <remarks>
    /// Используется для значений Id, не попавших ни в один из известных
    /// диапазонов (в частности, для <c>-5</c> и любых значений <c>&lt; -5</c>).
    /// </remarks>
    Unknown = -5,
}