namespace Nantuc.Kernel.Common;

/// <summary>
/// Набор опкодов виртуального процессора Nantuc.
/// </summary>
/// <remarks>
/// <para>
/// Каждая инструкция кодируется 32-битным словом, из которого декодер
/// (<c>InstructionDecoder</c>) извлекает сам опкод, номера регистров-операндов
/// и код размера данных. 64-битные непосредственные операнды (адреса, константы)
/// читаются из памяти сразу за словом инструкции и выравниваются по границе 8 байт.
/// </para>
/// <para>
/// Значение перечисления хранится в <see cref="byte"/>, поэтому корректный диапазон — 0..255.
/// </para>
/// <para>
/// Флаги <c>rFL</c> (Zero / Negative) в текущей реализации обновляются только
/// инструкциями <see cref="CMP"/> и <see cref="TEST"/>; арифметические и логические
/// инструкции флаги не изменяют.
/// </para>
/// </remarks>
public enum OpCode : byte
{
    // === 1. Системные команды ===

    /// <summary>
    /// Нет операции. Процессор просто переходит к следующей инструкции (пропуск такта).
    /// </summary>
    NOP,

    /// <summary>
    /// Остановка процессора / штатное завершение программы.
    /// </summary>
    /// <remarks>
    /// Сбрасывает флаг <c>IsRunning</c>. В отличие от <see cref="HALT"/> программа
    /// считается завершённой, а не приостановленной.
    /// </remarks>
    END,

    // === 2. Работа с памятью (Указатели и регистры) ===

    /// <summary>
    /// Копирование значения из регистра в регистр: <c>MOV R1, R2</c> → <c>R1 = R2</c>.
    /// </summary>
    MOV,

    /// <summary>
    /// Загрузка в регистр числа из памяти по абсолютному адресу: <c>LOAD R1, [addr]</c>.
    /// </summary>
    /// <remarks>
    /// Обращение проходит через проверяемый <c>MemoryBus</c>: при выходе за границы
    /// или нарушении выравнивания возвращается ошибка (SegmentationFault / AlignmentFault).
    /// </remarks>
    LOAD,

    /// <summary>
    /// Запись числа из регистра в память по абсолютному адресу: <c>STORE [addr], R2</c>.
    /// </summary>
    /// <remarks>
    /// Проверяемая запись через <c>MemoryBus</c>; ошибки доступа возвращаются как статус сбоя.
    /// </remarks>
    STORE,

    /// <summary>
    /// Загрузка непосредственной константы (Immediate) прямо в регистр: <c>LDI R1, 42</c>.
    /// </summary>
    /// <remarks>Константа — 64-битная и читается из потока инструкции.</remarks>
    LDI,

    /// <summary>
    /// Косвенная загрузка: <c>LOAD_IND R1, R2</c> → <c>R1 = [R2]</c>.
    /// </summary>
    /// <remarks>Эквивалентна <see cref="LOAD"/> с адресом, взятым из регистра.</remarks>
    LOAD_IND,

    /// <summary>
    /// Косвенная запись: <c>STORE_IND R1, R2</c> → <c>[R2] = R1</c>.
    /// </summary>
    /// <remarks>Эквивалентна <see cref="STORE"/> с адресом, взятым из регистра.</remarks>
    STORE_IND,

    // === 3. Арифметика и Логика (Тьюринг-базис) ===

    /// <summary>
    /// Сложение: <c>ADD R1, R2</c> → <c>R1 = R1 + R2</c>.
    /// </summary>
    /// <remarks>Флаги не изменяются; для сравнения используйте <see cref="CMP"/>.</remarks>
    ADD,

    /// <summary>
    /// Вычитание: <c>SUB R1, R2</c> → <c>R1 = R1 - R2</c>.
    /// </summary>
    /// <remarks>Флаги не изменяются; для сравнения используйте <see cref="CMP"/>.</remarks>
    SUB,

    /// <summary>
    /// Целочисленное умножение: <c>MULT_INT R1, R2</c> → <c>R1 = R1 * R2</c>.
    /// </summary>
    /// <remarks>Арифметика беззнаковая, переполнение отбрасывается (wrap-around).</remarks>
    MULT_INT,

    /// <summary>
    /// Логический сдвиг вправо: <c>SHR R1, R2</c> → <c>R1 = R1 &gt;&gt; R2</c>.
    /// </summary>
    /// <remarks>Величина сдвига берётся из младшего байта регистра <c>R2</c>.</remarks>
    SHR,

    /// <summary>
    /// Логический сдвиг влево: <c>SHL R1, R2</c> → <c>R1 = R1 &lt;&lt; R2</c>.
    /// </summary>
    /// <remarks>Величина сдвига берётся из младшего байта регистра <c>R2</c>.</remarks>
    SHL,

    /// <summary>
    /// Инкремент значения в регистре: <c>INC R1</c> → <c>R1 = R1 + 1</c>.
    /// </summary>
    INC,

    /// <summary>
    /// Декремент значения в регистре: <c>DEC R1</c> → <c>R1 = R1 - 1</c>.
    /// </summary>
    DEC,

    /// <summary>
    /// Целочисленное деление: <c>DIV R1, R2</c> → <c>R1 = R1 / R2</c>.
    /// </summary>
    /// <remarks>
    /// При нулевом делителе возвращается <c>BiosStatus.DivOnZero</c>.
    /// Деление беззнаковое, остаток отбрасывается (см. <see cref="MOD"/>).
    /// </remarks>
    DIV,

    // === 4. Логика (нужна для битовых масок и флагов) ===

    /// <summary>
    /// Побитовое И: <c>AND R1, R2</c> → <c>R1 = R1 &amp; R2</c>.
    /// </summary>
    AND,

    /// <summary>
    /// Побитовое ИЛИ: <c>OR R1, R2</c> → <c>R1 = R1 | R2</c>.
    /// </summary>
    OR,

    /// <summary>
    /// Побитовое исключающее ИЛИ: <c>XOR R1, R2</c> → <c>R1 = R1 ^ R2</c>.
    /// </summary>
    /// <remarks>Часто используется для обнуления регистра: <c>XOR R1, R1</c>.</remarks>
    XOR,

    /// <summary>
    /// Побитовое НЕ: <c>NOT R1</c> → <c>R1 = ~R1</c>.
    /// </summary>
    NOT,

    // === 5. Управление потоком (Ветвление и Указатели команд) ===

    /// <summary>
    /// Безусловный переход по абсолютному адресу: <c>JMP 0x05</c>.
    /// </summary>
    JMP,

    /// <summary>
    /// Переход по адресу, если установлен флаг нуля (результат последнего <see cref="CMP"/>/<see cref="TEST"/> равен нулю).
    /// </summary>
    JZ,

    /// <summary>
    /// Переход по адресу, если флаг нуля сброшен (результат последнего <see cref="CMP"/>/<see cref="TEST"/> не равен нулю).
    /// </summary>
    JNZ,

    /// <summary>
    /// Переход по адресу, если первое число больше второго:
    /// сброшены и флаг нуля, и флаг отрицательного результата.
    /// </summary>
    JG,

    /// <summary>
    /// Переход по адресу, если первое число меньше второго (установлен флаг отрицательного результата).
    /// </summary>
    JL,

    // === 6. Работа со Стеком (необходима для вызова функций) ===

    /// <summary>
    /// Положить значение регистра в стек: <c>PUSH R1</c>.
    /// </summary>
    /// <remarks>
    /// Указатель стека <c>rSP</c> уменьшается на 8. При коллизии с областью кучи
    /// (<c>rHP</c>) возвращается <c>BiosStatus.SegmentationFault</c>.
    /// </remarks>
    PUSH,

    /// <summary>
    /// Забрать значение из стека в регистр: <c>POP R1</c>.
    /// </summary>
    /// <remarks>Указатель стека <c>rSP</c> увеличивается на 8.</remarks>
    POP,

    /// <summary>
    /// Вызов подпрограммы: сохраняет адрес возврата в стек и выполняет переход по адресу.
    /// </summary>
    /// <remarks>
    /// При переполнении/коллизии стека с кучей возвращается <c>BiosStatus.SegmentationFault</c>.
    /// Парная инструкция — <see cref="RET"/>.
    /// </remarks>
    CALL,

    /// <summary>
    /// Возврат из подпрограммы: извлекает адрес возврата из стека в <c>rIP</c>.
    /// </summary>
    /// <remarks>При пустом стеке возвращается <c>BiosStatus.StackUnderflow</c>.</remarks>
    RET,

    // === 7. Ввод-вывод ===

    /// <summary>
    /// Чтение из порта: <c>IN Rdest, Rport</c> → <c>Rdest = порт[Rport]</c>.
    /// </summary>
    /// <remarks>Ошибка порта (например, отсутствующее устройство) возвращается как статус сбоя.</remarks>
    IN,

    /// <summary>
    /// Запись в порт: <c>OUT Rsrc, Rport</c> → <c>порт[Rport] = Rsrc</c>.
    /// </summary>
    /// <remarks>В порт передаётся младший байт регистра-источника.</remarks>
    OUT,

    /// <summary>
    /// Косвенный вызов: <c>CALL_IND R</c> → <c>CALL [R]</c>, где <c>[R]</c> — адрес цели в регистре.
    /// </summary>
    /// <remarks>Адрес цели проверяется на попадание в границы ОЗУ.</remarks>
    CALL_IND,

    /// <summary>
    /// Косвенный переход: <c>JMP_IND R</c> → <c>JMP [R]</c>, где <c>[R]</c> — адрес цели в регистре.
    /// </summary>
    /// <remarks>Адрес цели проверяется на попадание в границы ОЗУ.</remarks>
    JMP_IND,

    /// <summary>
    /// Приостановка процессора (переход в спящий режим) до пробуждения.
    /// </summary>
    /// <remarks>
    /// Устанавливает <c>IsSleeping</c>; выполнение инструкций прекращается до
    /// <see cref="WAKE"/> / <see cref="WAKE_INT"/> или внешней команды.
    /// </remarks>
    HALT,

    /// <summary>
    /// Пробуждение процессора из спящего режима (внешняя команда / BIOS).
    /// </summary>
    WAKE,

    /// <summary>
    /// Пробуждение процессора через устройство: <c>WAKE_INT R</c>, где <c>R</c> — идентификатор/адрес порта пробуждения.
    /// </summary>
    /// <remarks>Если порт не найден, возвращается <c>BiosStatus.NullDeviceOutput</c>.</remarks>
    WAKE_INT,

    // === Непроверяемые (быстрые) обращения к памяти ===

    /// <summary>
    /// Непроверяемая загрузка из памяти: <c>LOAD_UNSAFE R1, [addr]</c>.
    /// </summary>
    /// <remarks>
    /// Быстрый путь без проверки границ и прав доступа; корректность адреса
    /// целиком на совести программы. Используется ядром/BIOS на горячих путях.
    /// </remarks>
    LOAD_UNSAFE,

    /// <summary>
    /// Непроверяемая запись в память: <c>STORE_UNSAFE [addr], R2</c>.
    /// </summary>
    /// <remarks>Быстрый путь без проверки границ и прав доступа.</remarks>
    STORE_UNSAFE,

    /// <summary>
    /// Непроверяемая косвенная запись: <c>STORE_IND_UNSAFE R1, R2</c> → <c>[R2] = R1</c>.
    /// </summary>
    /// <remarks>Быстрый путь без проверки границ и прав доступа.</remarks>
    STORE_IND_UNSAFE,

    /// <summary>
    /// Непроверяемая косвенная загрузка: <c>LOAD_IND_UNSAFE R1, R2</c> → <c>R1 = [R2]</c>.
    /// </summary>
    /// <remarks>Быстрый путь без проверки границ и прав доступа.</remarks>
    LOAD_IND_UNSAFE,

    // === Сравнения и служебное ===

    /// <summary>
    /// Сравнение двух регистров: <c>CMP R1, R2</c>.
    /// </summary>
    /// <remarks>
    /// Вычисляет <c>R1 - R2</c> и обновляет флаги <c>rFL</c>:
    /// Zero — если разность равна нулю, Negative — если старший бит разности установлен.
    /// Регистры не изменяются. Используется вместе с <see cref="JZ"/>, <see cref="JNZ"/>, <see cref="JG"/>, <see cref="JL"/>.
    /// </remarks>
    CMP,

    /// <summary>
    /// Побитовая проверка двух регистров: <c>TEST R1, R2</c>.
    /// </summary>
    /// <remarks>
    /// Вычисляет <c>R1 &amp; R2</c> и обновляет флаги <c>rFL</c> (Zero / Negative).
    /// Регистры не изменяются. Аналог <see cref="CMP"/> для проверки отдельных битов.
    /// </remarks>
    TEST,

    /// <summary>
    /// Остаток от целочисленного деления: <c>MOD R1, R2</c> → <c>R1 = R1 % R2</c>.
    /// </summary>
    /// <remarks>При нулевом делителе возвращается <c>BiosStatus.DivOnZero</c>. Парная инструкция — <see cref="DIV"/>.</remarks>
    MOD,
}
