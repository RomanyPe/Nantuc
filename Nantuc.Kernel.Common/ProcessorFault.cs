namespace Nantuc.Kernel.Common;

/// <summary>
/// Неизменяемый снимок диагностической информации о причине остановки (сбоя) устройства/процессора.
/// </summary>
/// <remarks>
/// <para>
/// Формируется процессором при получении от обработчика инструкции статуса, отличного от
/// <see cref="BiosStatus.Success"/>, и далее передаётся в <c>IProcessorFaultPolicy.ShouldContinue</c>
/// для принятия решения о продолжении работы. Текущее значение доступно через
/// <c>Processor.GetDiagnosticData()</c>.
/// </para>
/// <para>
/// Это <b>не исключение</b>, а value-type снимок: копируется по стеку, не аллоцирует память,
/// пригоден для хранения в полях и передачи между потоками без блокировок.
/// </para>
/// <para>
/// <b>Соглашение о «неинициализированном» значении:</b> в текущей реализации в качестве
/// маркера «опкод неизвестен/отсутствует» используется <see cref="OpCode.NOP"/> (значение 0).
/// Это спорное решение, потому что <see cref="OpCode.NOP"/> — валидный опкод, и если
/// в будущем он начнёт приводить к сбою, отличить реальный <c>NOP</c> от «пустого» значения
/// будет невозможно. При первой возможности стоит заменить маркер на <c>OpCode?</c> или
/// отдельный член-сентинел.
/// </para>
/// </remarks>
/// <param name="Status">
/// Последний статус системы — причина остановки. Может быть как настоящей ошибкой
/// (<see cref="BiosStatus.SegmentationFault"/>, <see cref="BiosStatus.DivOnZero"/> и т.п.),
/// так и «не-ошибочным» кодом (<see cref="BiosStatus.EndProgramm"/>, <see cref="BiosStatus.InfinityLoop"/>),
/// которые проходят через тот же путь обработки.
/// </param>
/// <param name="FaultData">
/// Данные, полученные в момент сбоя: обычно адрес памяти, порт ввода-вывода или иной
/// контекст, релевантный конкретному статусу. Для статусов без контекста — <c>0</c>.
/// </param>
/// <param name="InstructionPointer">
/// Указатель на инструкцию (<c>rIP</c>), при выполнении которой произошёл сбой.
/// Позволяет сопоставить сбой с конкретным местом в программе.
/// </param>
/// <param name="OpCode">
/// Опкод инструкции, при выполнении которой произошёл сбой.
/// Значение <see cref="OpCode.NOP"/> в текущей реализации трактуется как «не инициализировано» —
/// см. &lt;remarks&gt; типа.
/// </param>
public readonly record struct ProcessorFault(
    BiosStatus Status,
    ulong FaultData,
    ulong InstructionPointer,
    OpCode OpCode);